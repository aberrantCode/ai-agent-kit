#!/usr/bin/env python3
"""cc_transcripts -- shared, stdlib-only library for reading Claude Code transcripts.

Every session-manager script that reads ``~/.claude/projects`` (audit, mine, resume,
usage) imports this module instead of re-deriving discovery, JSONL iteration and the
counting fixes. Python 3.10+, no third-party dependencies, read-only: nothing here
ever writes to a transcript tree.

On-disk layout (see ../references/transcript-data-model.md for the long version)::

    ~/.claude/projects/<slug>/<session-id>.jsonl                  main transcript (may be MISSING)
    ~/.claude/projects/<slug>/<session-id>/subagents/agent-<h>.meta.json
    ~/.claude/projects/<slug>/<session-id>/subagents/agent-<h>.jsonl
    ~/.claude/projects/<slug>/<session-id>/subagents/workflows/wf_<runid>/agent-<h>.meta.json

How a script locates this module (no PYTHONPATH needed)::

    sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                    "..", "..", "transcripts", "scripts"))
    import cc_transcripts as cct

API at a glance
---------------
paths/discovery : projects_root, slugify, to_posix, msys_to_native, project_dirs,
                  jsonl_files, session_files, iter_sessions, parse_since
records         : iter_records, iter_messages, iter_tool_uses (ToolUse), session_cwd,
                  project_cwd, parse_timestamp, usage_tokens
text            : first_text, all_text, INJECTED_PREFIXES, is_injected
worktrees       : common_dir, registered_worktrees, worktree_project_dirs
subagents       : load_json, subagent_meta_paths, parse_meta_path

Gotchas (every one of these has bitten a real analysis; the first two are COUNTING BUGS)
-----------------------------------------------------------------------------------------
1. ``**`` matches ZERO directories. ``glob("<dir>/**/*.meta.json", recursive=True)`` also
   returns top-level files, so combining it with a non-recursive ``glob("<dir>/*.meta.json")``
   counts every top-level file twice. Use ONE recursive glob (``subagent_meta_paths`` does)
   and dedupe by path. A naive per-Workflow-block re-glob inflated a real 96-dispatch
   window to 190+, and the inflated numbers still "look plausible".
2. A session can fire the ``Workflow`` tool_use block several times for the SAME run
   (``resumeFromRunId`` continuation, or a "re-run this workflow" retry). Attribute a run's
   agents ONCE, keyed by the ``wf_<runid>`` directory (``parse_meta_path()['wf_dir']``), never
   once per Workflow tool_use occurrence -- otherwise the same N agents are multiplied by the
   number of invocations.
3. meta.json is ground truth for "was a subagent spawned"; the parent transcript is not.
   A still-open/concurrent/background session's parent ``.jsonl`` can be stale or MISSING
   while its dispatch records already exist. Window dispatches by the meta.json mtime, NOT the
   parent jsonl mtime (``subagent_meta_paths`` does). When the parent is missing, report the
   main model as "unknown (parent jsonl not found)" -- never fabricate it, never drop the record.
4. ``model`` is ABSENT (not null, not "unset") in meta.json when the dispatch did not choose
   one (= inherited the caller's model). Always ``m.get("model", "unset")``.
5. Nested delegation: a subagent can dispatch further subagents; its meta.json carries
   ``parentAgentId`` and an incremented ``spawnDepth``. Do not flatten these away.
6. Workflow-inner agents have no ``toolUseId`` (they are generated by the Workflow runtime and
   are not addressable tool_use blocks); group them by ``wf_<runid>``.
7. The project directory name is a LOSSY encoding of the launch cwd (``slugify``: every
   non-alphanumeric char becomes ``-``; ``_``, ``:``, ``\\``, ``/``, ``.`` all collide). NEVER
   decode a slug; read the real ``cwd`` field from the records (``session_cwd`` /
   ``project_cwd``).
8. A git worktree lands in its OWN sibling slug dir. This workstation has three conventions
   (in-repo ``.worktrees/``, sibling ``<repo>-wt``, shared containers that hold several repos'
   worktrees). Correlate by git identity (``git rev-parse --git-common-dir``), not by name --
   see ``worktree_project_dirs``.
9. Path separators: on Windows, ``os.path`` yields backslashes but jsonl/meta parsing that
   ``split("/")``s or substring-matches needs forward slashes; normalise with ``to_posix``.
10. git-bash path-translation trap: ``/c/Users/...`` works as a separate argv (MSYS translates
    it) but the same string embedded in ``python -c`` / a heredoc is NOT translated and native
    Windows Python silently sees nothing (``glob`` -> ``[]``, ``exists`` -> False). Build paths
    with ``os.path.expanduser`` (``projects_root``) or take them from argv; ``msys_to_native``
    repairs a stray ``/c/...`` string.
11. ``type: "user"`` is overloaded: genuine operator turns, ``tool_result`` blocks, AND harness
    injections (``<system-reminder>``, hook output, skill bodies "Base directory for this
    skill", ``<local-command-caveat>``, compaction "This session is being continued", Honcho
    memory). Filter with ``is_injected``; without it injections drown real turns ~80:1. A
    user turn whose content list holds a ``tool_result`` block is not operator text either.
12. ``isSidechain: true`` records are subagent turns, not the operator's thread -- skip them
    (``skip_sidechains=True``) unless you are deliberately auditing agent-dispatched work.
13. Trust a tool_result's ``is_error`` flag, never content-sniffing (a verifier printing
    ``errors: 0`` is not a failure). ``Cancelled: parallel tool call`` errors are downstream
    noise from a failed sibling; count them separately.
14. Schema drift across CLI versions: ``message`` may be absent or a string, ``content`` may be
    a str or a list, ``usage`` / ``model`` / ``cwd`` / ``gitBranch`` / ``timestamp`` may be
    missing, the Task tool is called ``Agent`` in newer versions (``DISPATCH_TOOL_NAMES``).
    Guard every key access; the iterators here skip malformed lines and non-dict records.
15. Token accounting: ``usage_tokens`` treats missing/None buckets as 0. The first-turn context
    is input + cache_read + cache_creation. Transcript timestamps end in ``Z`` which
    ``datetime.fromisoformat`` rejects before 3.11 -- use ``parse_timestamp``.
16. A session launched in repo A may ``cd`` into repo B and do all its real work there; the
    transcript still lives under A's slug. Judge by the files edited, not the slug.
17. A compacted / handed-off session ends with a baton ("This session is being continued
    ..."); the live thread is the NEWER session in the chain.
18. ``project_substring`` filters here match the project slug (case-sensitive); to filter by
    real working directory read ``project_cwd`` and compare yourself (usage-report does, and
    case-insensitively).
"""
from __future__ import annotations

import glob
import json
import os
import re
import subprocess
from collections import namedtuple
from datetime import datetime
from typing import Iterator

__all__ = [
    "DISPATCH_TOOL_NAMES", "INJECTED_PREFIXES", "ToolUse",
    "projects_root", "slugify", "to_posix", "msys_to_native",
    "project_dirs", "jsonl_files", "session_files", "iter_sessions", "parse_since",
    "iter_records", "iter_messages", "iter_tool_uses", "session_cwd", "project_cwd",
    "parse_timestamp", "usage_tokens",
    "first_text", "all_text", "is_injected",
    "common_dir", "registered_worktrees", "worktree_project_dirs",
    "load_json", "subagent_meta_paths", "parse_meta_path",
]

# The subagent-dispatch tool names ("Task" was renamed "Agent"; "Workflow" runs scripts).
DISPATCH_TOOL_NAMES = ("Task", "Agent", "Workflow")

# Hook-injected / non-human `type:user` content -- never a genuine operator turn.
INJECTED_PREFIXES = (
    "<system-reminder>", "[honcho memory", "[request interrupted",
    "caveat:", "<command-name>", "<command-message>", "<local-command-stdout>",
    "<local-command-caveat>", "base directory for this skill",
    "this session is being continued", "launching skill:", "tool loaded.",
    "<user-prompt-submit-hook>", "your questions have been answered",
)

ToolUse = namedtuple("ToolUse", "id ts model name input")


# --------------------------------------------------------------------------- paths

def projects_root(root: str | None = None) -> str:
    """`root` if given, else ``~/.claude/projects``. Resolved at CALL time so HOME /
    USERPROFILE overrides (tests, fake homes) are honoured."""
    if root:
        return root
    return os.path.join(os.path.expanduser("~"), ".claude", "projects")


def slugify(path: str) -> str:
    """The CLI's project-dir encoding: every non-alphanumeric char -> ``-``.

    LOSSY (``C:\\a_b`` and ``C:\\a-b`` collide) -- use it to go path -> slug only, never
    slug -> path. Recover the real directory from the records' ``cwd`` field."""
    return re.sub(r"[^A-Za-z0-9]", "-", path)


def to_posix(path: str) -> str:
    """Backslash -> forward slash. Windows ``os.path``/``glob`` return mixed separators;
    code that ``split("/")``s or substring-matches paths must normalise first."""
    return str(path).replace("\\", "/")


def msys_to_native(path: str) -> str:
    """Repair a git-bash style ``/c/Users/x`` string to ``C:/Users/x`` on Windows (no-op
    elsewhere and for already-native paths). MSYS only translates argv, not strings embedded
    in ``python -c`` code."""
    if os.name == "nt":
        m = re.match(r"^/([A-Za-z])(/.*)?$", path)
        if m:
            return f"{m.group(1).upper()}:{m.group(2) or '/'}"
    return path


def project_dirs(root: str | None = None, substring: str | None = None) -> list[str]:
    """Project directories under the projects root, in directory (listdir) order. Missing
    root -> []. `substring` (case-sensitive) filters on the slug."""
    base = projects_root(root)
    try:
        names = os.listdir(base)
    except OSError:
        return []
    out = []
    for name in names:
        if substring and substring not in name:
            continue
        p = os.path.join(base, name)
        if os.path.isdir(p):
            out.append(p)
    return out


def jsonl_files(project_dir: str) -> list[str]:
    """``*.jsonl`` paths directly in `project_dir`, in directory (listdir) order, unsorted.
    (Subagent transcripts live deeper and are not returned.)"""
    try:
        names = os.listdir(project_dir)
    except OSError:
        return []
    return [os.path.join(project_dir, n) for n in names if n.endswith(".jsonl")]


def session_files(project_dir: str) -> list[tuple[str, float]]:
    """``(path, mtime)`` for each ``*.jsonl`` directly in `project_dir`, newest first (stable
    for equal mtimes). Unstat-able files are skipped."""
    out = []
    for p in jsonl_files(project_dir):
        try:
            out.append((p, os.path.getmtime(p)))
        except OSError:
            pass
    out.sort(key=lambda x: x[1], reverse=True)
    return out


def parse_since(value) -> float | None:
    """Epoch float. Accepts None (-> None), int/float, ``datetime`` (naive = local time), or
    a local-time string ``"YYYY-MM-DD HH:MM:SS"`` (also ``"YYYY-MM-DD"``). Raises ValueError."""
    if value is None:
        return None
    if isinstance(value, bool):
        raise ValueError(f"unsupported since value: {value!r}")
    if isinstance(value, (int, float)):
        return float(value)
    if isinstance(value, datetime):
        return value.timestamp()
    if isinstance(value, str):
        for fmt in ("%Y-%m-%d %H:%M:%S", "%Y-%m-%d"):
            try:
                return datetime.strptime(value, fmt).timestamp()
            except ValueError:
                continue
    raise ValueError(f"unsupported since value: {value!r}")


def iter_sessions(root: str | None = None, since=None, project_substring: str | None = None
                  ) -> Iterator[tuple[str, str, str, float]]:
    """Yield ``(path, project_slug, session_id, mtime)`` for every main transcript across the
    project dirs whose mtime >= `since` (see ``parse_since``). Directory order, NOT sorted."""
    cutoff = parse_since(since)
    for pdir in project_dirs(root, project_substring):
        slug = os.path.basename(pdir)
        for p in jsonl_files(pdir):
            try:
                mt = os.path.getmtime(p)
            except OSError:
                continue
            if cutoff is not None and mt < cutoff:
                continue
            yield p, slug, os.path.splitext(os.path.basename(p))[0], mt


# ------------------------------------------------------------------------ records

def iter_records(path: str, errors: str = "replace", stats: dict | None = None) -> Iterator[dict]:
    """Yield each JSON object (dict) of a JSONL file. Blank lines, malformed lines and
    non-dict records are skipped; an unreadable file yields nothing. Streams line by line
    (flat memory). If `stats` is given it receives ``lines`` (physical lines read, blank and
    malformed included) and ``bad`` (malformed lines)."""
    if stats is not None:
        stats.setdefault("lines", 0)
        stats.setdefault("bad", 0)
    try:
        with open(path, "r", encoding="utf-8", errors=errors) as fh:
            for line in fh:
                if stats is not None:
                    stats["lines"] += 1
                line = line.strip()
                if not line:
                    continue
                try:
                    rec = json.loads(line)
                except ValueError:
                    if stats is not None:
                        stats["bad"] += 1
                    continue
                if isinstance(rec, dict):
                    yield rec
    except OSError:
        return


def iter_messages(path: str, role: str | None = None, skip_sidechains: bool = False,
                  stats: dict | None = None) -> Iterator[tuple[dict, dict]]:
    """Yield ``(record, message_dict)`` for records whose ``message`` is a dict. `role`
    matches ``message["role"]``; `skip_sidechains` drops ``isSidechain`` records."""
    for rec in iter_records(path, stats=stats):
        if skip_sidechains and rec.get("isSidechain"):
            continue
        msg = rec.get("message")
        if not isinstance(msg, dict):
            continue
        if role is not None and msg.get("role") != role:
            continue
        yield rec, msg


def iter_tool_uses(path: str, names=None) -> Iterator[ToolUse]:
    """Yield ``ToolUse(id, ts, model, name, input)`` for each ``tool_use`` content block in a
    transcript. `names` restricts to those tool names (None = all). ``model`` is the carrying
    message's model (default "unknown"); ``input`` is always a dict."""
    for rec, msg in iter_messages(path):
        content = msg.get("content")
        if not isinstance(content, list):
            continue
        model = msg.get("model", "unknown")
        ts = rec.get("timestamp", "")
        for block in content:
            if (isinstance(block, dict) and block.get("type") == "tool_use"
                    and (names is None or block.get("name") in names)):
                yield ToolUse(block.get("id"), ts, model, block.get("name"),
                              block.get("input", {}) or {})


def session_cwd(path: str):
    """The ``cwd`` of the first record in the file that carries one (else None)."""
    for rec in iter_records(path):
        if rec.get("cwd"):
            return rec["cwd"]
    return None


def project_cwd(project_dir: str, newest_only: bool = False):
    """The real working directory behind a project dir (never decode the slug!). Default:
    first cwd found across the dir's ``*.jsonl`` files in directory order. With
    `newest_only`, consult only the newest file."""
    files = jsonl_files(project_dir)
    if newest_only:
        stamped = []
        for p in files:
            try:
                stamped.append((p, os.path.getmtime(p)))
            except OSError:
                pass
        stamped.sort(key=lambda x: x[1], reverse=True)
        files = [p for p, _ in stamped[:1]]
    for p in files:
        cwd = session_cwd(p)
        if cwd:
            return cwd
    return None


def parse_timestamp(ts):
    """Transcript ISO timestamp -> aware ``datetime``; None if missing/malformed. (Trailing
    ``Z`` is rewritten to ``+00:00`` because ``fromisoformat`` rejects it before py3.11.)"""
    if not ts:
        return None
    try:
        return datetime.fromisoformat(ts.replace("Z", "+00:00"))
    except (ValueError, TypeError, AttributeError):
        return None


def usage_tokens(usage: dict):
    """``(input, output, cache_read, cache_creation)`` from a usage dict; missing/None -> 0."""
    return (usage.get("input_tokens") or 0,
            usage.get("output_tokens") or 0,
            usage.get("cache_read_input_tokens") or 0,
            usage.get("cache_creation_input_tokens") or 0)


# --------------------------------------------------------------------------- text

def first_text(content) -> str:
    """The first ``text`` block of a message ``content`` (str passes through; else "")."""
    if isinstance(content, str):
        return content
    if isinstance(content, list):
        for b in content:
            if isinstance(b, dict) and b.get("type") == "text":
                return b.get("text", "")
    return ""


def all_text(content) -> str:
    """All ``text`` blocks of a message ``content`` joined with newlines."""
    if isinstance(content, str):
        return content
    out = []
    if isinstance(content, list):
        for b in content:
            if isinstance(b, dict) and b.get("type") == "text":
                out.append(b.get("text", ""))
    return "\n".join(out)


def is_injected(text: str, prefixes=INJECTED_PREFIXES) -> bool:
    """True if a user turn is a harness injection rather than operator text (gotcha 11)."""
    return text.lstrip().lower().startswith(tuple(prefixes))


# ------------------------------------------------------------------------ worktrees

def _norm(p: str) -> str:
    """Case/separator-normalised absolute path for reliable comparison."""
    try:
        return os.path.normcase(os.path.abspath(os.path.realpath(p)))
    except Exception:
        return os.path.normcase(os.path.abspath(p))


def _git(args, cwd=None) -> str:
    try:
        return subprocess.run(
            ["git"] + args, cwd=cwd, capture_output=True, text=True, timeout=15
        ).stdout
    except Exception:
        return ""


def common_dir(path: str):
    """The git *common* dir for `path` -- the origin repo's real .git. For any worktree this
    resolves to the MAIN checkout's .git, so it is the identity two worktrees of the same repo
    share. Returns a normalised path or None."""
    out = _git(["-C", path, "rev-parse", "--git-common-dir"]).strip()
    if not out:
        return None
    if not os.path.isabs(out):
        out = os.path.join(path, out)
    return _norm(out)


def registered_worktrees(repo: str):
    """Paths of every worktree git still tracks for `repo` -- live AND removed-but-not-yet-
    pruned -- regardless of naming convention or location."""
    paths = []
    for line in _git(["-C", repo, "worktree", "list", "--porcelain"]).splitlines():
        if line.startswith("worktree "):
            paths.append(os.path.abspath(line[len("worktree "):].strip()))
    return paths


def worktree_project_dirs(repo: str, root: str | None = None) -> dict:
    """Return ``{slug: path}`` for every place THIS repo's sessions live -- across all three
    worktree conventions on this workstation:

      - in-repo ``<repo>/.worktrees/<name>``
      - sibling ``<repo>-wt/<name>`` (or ``<repo>-wt`` itself)
      - shared containers ``C:\\development\\.worktrees\\<name>`` and
        ``C:\\development\\github-repos-wt\\<name>`` that hold worktrees for *several* repos

    Correlation is git-authoritative, not name-based, because the shared containers do not
    embed the origin repo in their path:

      1. the main checkout;
      2. ``git worktree list`` -- every worktree git tracks (live + prunable), any
         convention/location;
      3. recovery for worktrees git has already PRUNED but whose transcripts remain: scan
         worktree-shaped project dirs and attribute each by identity -- a dir whose slug embeds
         this repo (``<mainslug>--worktrees-`` / ``<mainslug>-wt``) is trusted; a shared-
         container dir is included only if its recorded cwd still resolves (via git-common-dir)
         to THIS repo.

    Residual edge: a worktree that was pruned AND lived in a shared container AND whose
    directory is now deleted cannot be attributed (no git trace, no resolvable cwd).
    """
    base = projects_root(root)
    main = os.path.abspath(repo)
    mainslug = slugify(main)
    slugs = {mainslug: main}
    tcommon = common_dir(repo)

    # (2) git-tracked worktrees -- convention-independent, absolute paths
    for p in registered_worktrees(repo):
        slugs.setdefault(slugify(p), p)

    # (3) pruned-but-transcripts-remain recovery
    try:
        names = os.listdir(base)
    except OSError:
        names = []
    for name in names:
        if name in slugs:
            continue
        looks_wt = ("--worktrees-" in name) or ("-wt-" in name) or name.endswith("-wt")
        if not looks_wt:
            continue
        embeds_repo = name.startswith(mainslug + "--worktrees-") or name.startswith(mainslug + "-wt")
        cwd = project_cwd(os.path.join(base, name), newest_only=True)
        if embeds_repo:
            slugs.setdefault(name, cwd or name)          # name attributes it
        elif tcommon and cwd and os.path.isdir(cwd) and common_dir(cwd) == tcommon:
            slugs.setdefault(name, cwd)                  # git-verified membership
    return slugs


# ------------------------------------------------------------------------ subagents

def load_json(path: str):
    """Parsed JSON file, or None if missing/unreadable/malformed."""
    try:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return None


def subagent_meta_paths(root: str | None = None, since=None,
                        project_substring: str | None = None) -> list[str]:
    """Posix-normalised, de-duplicated paths of every subagent ``*.meta.json`` under the
    projects root whose own mtime >= `since`. ONE recursive glob (gotcha 1: ``**`` matches
    zero dirs, so a second non-recursive glob would double-count top-level files). Filtered on
    the meta.json mtime, not the parent jsonl's (gotcha 3). `project_substring` matches the
    project slug."""
    base = to_posix(projects_root(root))
    cutoff = parse_since(since)
    pattern = glob.escape(base) + "/*/*/subagents/**/*.meta.json"
    seen: set[str] = set()
    out = []
    for p in glob.glob(pattern, recursive=True):
        p = to_posix(p)
        if p in seen:
            continue
        seen.add(p)
        if cutoff is not None:
            try:
                if os.path.getmtime(p) < cutoff:
                    continue
            except OSError:
                continue
        if project_substring:
            rel = p[len(base):].lstrip("/") if p.startswith(base) else p
            if project_substring not in rel.split("/", 1)[0]:
                continue
        out.append(p)
    return out


def parse_meta_path(path: str, root: str | None = None) -> dict:
    """Decompose a meta.json path into ``project`` (slug), ``session`` (id), ``project_dir``,
    ``is_workflow_inner`` and ``wf_dir`` (the ``wf_<runid>`` dir for workflow-inner agents,
    else None). With `root`, positions are taken relative to it; otherwise they are anchored on
    the ``subagents`` path component."""
    parts = to_posix(path).split("/")
    if root:
        nroot = len(to_posix(projects_root(root)).rstrip("/").split("/"))
        proj_idx = nroot - 1            # index just before the slug
    else:
        sub_idx = parts.index("subagents", 2)
        proj_idx = sub_idx - 3          # slug at proj_idx+1, session at proj_idx+2
    project = parts[proj_idx + 1]
    session = parts[proj_idx + 2]
    project_dir = "/".join(parts[:proj_idx + 2])
    rest = parts[proj_idx + 3:]
    is_wf = "workflows" in rest
    wf_dir = None
    if is_wf:
        wf_i = parts.index("workflows", proj_idx + 3)
        wf_dir = parts[wf_i + 1] if len(parts) > wf_i + 1 else None
    return {"project": project, "session": session, "project_dir": project_dir,
            "is_workflow_inner": is_wf, "wf_dir": wf_dir}
